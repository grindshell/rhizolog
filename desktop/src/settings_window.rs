/// Everything here is short and most of it is a number, but two of the strings
/// are somebody else's: an environment variable and an error message that
/// quotes what was typed into the box.
fn escape(text: &str) -> String {
    let mut escaped = String::with_capacity(text.len());

    for character in text.chars() {
        match character {
            '&' => escaped.push_str("&amp;"),
            '<' => escaped.push_str("&lt;"),
            '>' => escaped.push_str("&gt;"),
            '"' => escaped.push_str("&quot;"),
            '\'' => escaped.push_str("&#39;"),
            other => escaped.push(other),
        }
    }

    escaped
}

fn html(status: StatusCode, body: Vec<u8>) -> Response<Cow<'static, [u8]>> {
    Response::builder()
        .status(status)
        // The page states the port the server is on, which the form it carries
        // is in the business of changing.
        .header(header::CACHE_CONTROL, "no-store")
        .header(header::CONTENT_TYPE, "text/html; charset=utf-8")
        .body(Cow::Owned(body))
        .expect("a response with a valid status and headers")
}

fn plain(status: StatusCode, body: &'static str) -> Response<Cow<'static, [u8]>> {
    Response::builder()
        .status(status)
        .header(header::CACHE_CONTROL, "no-store")
        .header(header::CONTENT_TYPE, "text/plain; charset=utf-8")
        .body(Cow::Borrowed(body.as_bytes()))
        .expect("a response with a valid status and headers")
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The whole form, and the reason it is one box: nothing typed is a
    /// perfectly ordinary answer rather than a mistake.
    #[test]
    fn an_empty_box_is_automatic() {
        assert_eq!(read_form(b"port="), Ok(Choice::Automatic));
        assert_eq!(read_form(b"port=  "), Ok(Choice::Automatic));
    }

    #[test]
    fn a_number_is_a_port() {
        assert_eq!(read_form(b"port=8080"), Ok(Choice::Fixed(8080)));
        assert_eq!(read_form(b"port=1"), Ok(Choice::Fixed(1)));
        assert_eq!(read_form(b"port=65535"), Ok(Choice::Fixed(65535)));
    }

    /// Every one of these is something a hand-written post could say, and none
    /// of them may become a port the app then fails to bind on every launch.
    #[test]
    fn anything_that_is_not_a_port_is_refused() {
        for body in [
            &b"port=0"[..],
            b"port=65536",
            b"port=-1",
            b"port=3000.5",
            b"port=three thousand",
            b"port=3000%3B",
        ] {
            assert!(
                read_form(body).is_err(),
                "{:?} was accepted",
                String::from_utf8_lossy(body)
            );
        }
    }

    #[test]
    fn a_form_without_a_port_is_refused() {
        assert!(read_form(b"").is_err());
        assert!(read_form(b"wiki_root=%2Ftmp").is_err());
    }

    /// The field is found by name rather than by position, because a browser
    /// orders a form's fields however it likes and this one will grow.
    #[test]
    fn the_port_is_found_among_other_fields() {
        assert_eq!(read_form(b"other=1&port=8080"), Ok(Choice::Fixed(8080)));
        assert_eq!(read_form(b"port=8080&other=1"), Ok(Choice::Fixed(8080)));
    }

    /// What is stored is `None` for automatic, which is what
    /// [`crate::listen_for`] turns back into a preference rather than a
    /// requirement.
    #[test]
    fn automatic_is_stored_as_nothing() {
        assert_eq!(Choice::Automatic.port(), None);
        assert_eq!(Choice::Fixed(8080).port(), Some(8080));
    }

    /// A window label has to be unique, and a settings window that collided
    /// with a page window would simply fail to open.
    #[test]
    fn the_label_cannot_collide_with_a_page_window() {
        assert_ne!(LABEL, "main");
        assert!(!crate::label_for(&url()).starts_with(LABEL));
    }

    /// `RHIZOLOG_ADDR` is printed into the page, and it is a string from
    /// outside the app.
    #[test]
    fn the_page_escapes_what_it_did_not_write() {
        let page = String::from_utf8(document(&View {
            choice: Choice::Fixed(8080),
            address: None,
            forced: Some("<script>alert(1)</script>".to_owned()),
            complaint: Some("\"quoted\" & <angled>"),
        }))
        .expect("the page is utf-8");

        assert!(!page.contains("<script>"), "{page}");
        assert!(page.contains("&lt;script&gt;"));
        assert!(page.contains("&quot;quoted&quot; &amp; &lt;angled&gt;"));
    }

    /// The value has to survive into the box, or opening the window would look
    /// like the setting had been forgotten.
    #[test]
    fn the_page_shows_the_port_it_was_given() {
        let page = String::from_utf8(document(&View {
            choice: Choice::Fixed(8080),
            address: "127.0.0.1:8080".parse().ok(),
            forced: None,
            complaint: None,
        }))
        .expect("the page is utf-8");

        assert!(page.contains("value=\"8080\""), "{page}");
        assert!(page.contains("http://127.0.0.1:8080"));
        // The attribute rather than the word: the stylesheet has `:disabled`
        // rules in it either way.
        assert!(page.contains("autofocus>"), "the box is usable");
        assert!(
            page.contains("<button type=\"submit\">"),
            "so is the button"
        );
    }

    /// A control that cannot be honoured is worse than one that is not offered,
    /// so the environment switches the form off rather than letting somebody
    /// save a setting that will be ignored.
    #[test]
    fn the_environment_disables_the_form() {
        let page = String::from_utf8(document(&View {
            choice: Choice::Automatic,
            address: None,
            forced: Some("127.0.0.1:9999".to_owned()),
            complaint: None,
        }))
        .expect("the page is utf-8");

        assert!(page.contains("<button type=\"submit\" disabled>"), "{page}");
        assert!(page.contains("autofocus disabled>"));
        assert!(
            page.contains("value=\"\""),
            "automatic leaves the box empty"
        );
    }
}
